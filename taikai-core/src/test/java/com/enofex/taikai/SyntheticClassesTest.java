package com.enofex.taikai;

import static com.tngtech.archunit.core.domain.JavaModifier.ABSTRACT;
import static com.tngtech.archunit.core.domain.JavaModifier.FINAL;
import static com.tngtech.archunit.core.domain.JavaModifier.SYNTHETIC;
import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.tngtech.archunit.base.DescribedPredicate;
import com.tngtech.archunit.core.domain.JavaClass;
import com.tngtech.archunit.core.domain.JavaClasses;
import com.tngtech.archunit.core.importer.ClassFileImporter;
import java.util.List;
import java.util.function.Consumer;
import java.util.logging.Logger;
import java.util.stream.Stream;
import org.jspecify.annotations.NullMarked;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.springframework.web.bind.annotation.RestController;

/**
 * Classes generated by the compiler, such as the {@code package-info} class of an annotated
 * {@code package-info.java} and the class javac generates for a {@code switch} over an enum, must
 * not be reported by rules that check the selected classes themselves.
 */
class SyntheticClassesTest {

  private static final String PACKAGE = "com.enofex.taikai.synthetic.web";
  private static final DescribedPredicate<JavaClass> WEB = ClassCriteria.inPackage(
      "..synthetic.web..");
  private static final JavaClasses CLASSES = new ClassFileImporter().importPackages(PACKAGE);

  @Test
  void shouldImportSyntheticClasses() {
    assertTrue(CLASSES.get(PACKAGE + ".package-info").getModifiers().contains(SYNTHETIC));
    assertTrue(CLASSES.get(PACKAGE + ".TrafficController$1").getModifiers().contains(SYNTHETIC));
  }

  @ParameterizedTest(name = "{0}")
  @MethodSource("rules")
  void shouldIgnoreSyntheticClasses(String rule, Consumer<Taikai.Builder> configuration) {
    Taikai.Builder builder = Taikai.builder().classes(CLASSES);
    configuration.accept(builder);

    assertDoesNotThrow(builder.build()::check);
  }

  static Stream<Arguments> rules() {
    return Stream.of(
        rule("classesShouldMatch", builder -> builder.java(java -> java
            .naming(naming -> naming.classesShouldMatch(".*Controller")))),
        rule("classesShouldMatch with criteria", builder -> builder.java(java -> java
            .naming(naming -> naming.classesShouldMatch(WEB, ".*Controller")))),
        rule("classesShouldNotMatch", builder -> builder.java(java -> java
            .naming(naming -> naming.classesShouldNotMatch(".*\\$\\d+")))),
        rule("classesShouldNotMatch with criteria", builder -> builder.java(java -> java
            .naming(naming -> naming.classesShouldNotMatch(WEB, ".*\\$\\d+")))),
        rule("classesShouldBeAnnotatedWith", builder -> builder.java(java -> java
            .classesShouldBeAnnotatedWith(WEB, RestController.class))),
        rule("classesShouldNotBeAnnotatedWith", builder -> builder.java(java -> java
            .classesShouldNotBeAnnotatedWith(WEB, NullMarked.class))),
        rule("classesShouldHaveField", builder -> builder.java(java -> java
            .classesShouldHaveField(WEB, FieldCriteria.nameMatching("LOGGER")))),
        rule("classesShouldHaveModifiers", builder -> builder.java(java -> java
            .classesShouldHaveModifiers(WEB, List.of(FINAL)))),
        rule("classesShouldNotHaveModifiers", builder -> builder.java(java -> java
            .classesShouldNotHaveModifiers(WEB, List.of(ABSTRACT)))),
        rule("classesShouldBeAssignableTo", builder -> builder.java(java -> java
            .classesShouldBeAssignableTo(WEB, Runnable.class))),
        rule("classesShouldImplement", builder -> builder.java(java -> java
            .classesShouldImplement(WEB, Runnable.class))),
        rule("shouldImport", builder -> builder.java(java -> java
            .imports(imports -> imports.shouldImport(WEB,
                ClassCriteria.inPackage("..synthetic.model.."))))),
        rule("classesShouldUseLogger", builder -> builder.logging(logging -> logging
            .classesShouldUseLogger(WEB, Logger.class))),
        rule("shouldBeAnnotatedWithRestController", builder -> builder.spring(spring -> spring
            .controllers(controllers -> controllers.shouldBeAnnotatedWithRestController(WEB)))));
  }

  private static Arguments rule(String name, Consumer<Taikai.Builder> configuration) {
    return Arguments.of(name, configuration);
  }
}
