package com.enofex.taikai.internal;

import com.tngtech.archunit.core.domain.JavaModifier;
import com.tngtech.archunit.core.domain.properties.HasModifiers;
import java.util.Collection;
import java.util.stream.Collectors;

/**
 * Checks the modifiers of classes and their members.
 */
public final class Modifiers {

  private Modifiers() {
  }

  /**
   * Returns whether a class or member is public.
   *
   * @param element the class or member
   * @return whether the element is public
   */
  public static boolean isPublic(HasModifiers element) {
    return element.getModifiers().contains(JavaModifier.PUBLIC);
  }

  /**
   * Returns whether a class or member is protected.
   *
   * @param element the class or member
   * @return whether the element is protected
   */
  public static boolean isProtected(HasModifiers element) {
    return element.getModifiers().contains(JavaModifier.PROTECTED);
  }

  /**
   * Returns whether a class or member is private.
   *
   * @param element the class or member
   * @return whether the element is private
   */
  public static boolean isPrivate(HasModifiers element) {
    return element.getModifiers().contains(JavaModifier.PRIVATE);
  }

  /**
   * Returns whether a class or member is final.
   *
   * @param element the class or member
   * @return whether the element is final
   */
  public static boolean isFinal(HasModifiers element) {
    return element.getModifiers().contains(JavaModifier.FINAL);
  }

  /**
   * Returns whether a class or method is abstract.
   *
   * @param element the class or method
   * @return whether the element is abstract
   */
  public static boolean isAbstract(HasModifiers element) {
    return element.getModifiers().contains(JavaModifier.ABSTRACT);
  }

  /**
   * Returns whether a class or member is static.
   *
   * @param element the class or member
   * @return whether the element is static
   */
  public static boolean isStatic(HasModifiers element) {
    return element.getModifiers().contains(JavaModifier.STATIC);
  }

  /**
   * Returns whether a class or member is synthetic, that is generated by the compiler.
   *
   * @param element the class or member
   * @return whether the element is synthetic
   */
  public static boolean isSynthetic(HasModifiers element) {
    return element.getModifiers().contains(JavaModifier.SYNTHETIC);
  }

  /**
   * Returns whether a method is a bridge method, which the compiler generates when a method
   * overrides a method of a generic type with other parameter types after erasure.
   *
   * @param method the method
   * @return whether the method is a bridge method
   */
  public static boolean isBridge(HasModifiers method) {
    return method.getModifiers().contains(JavaModifier.BRIDGE);
  }

  /**
   * Returns the names of the given modifiers in their order, separated by commas, as rule
   * descriptions and violation messages show them.
   *
   * @param modifiers the modifiers
   * @return the names, for example {@code PUBLIC, STATIC}
   */
  public static String names(Collection<JavaModifier> modifiers) {
    return modifiers.stream().map(Enum::name).collect(Collectors.joining(", "));
  }
}
